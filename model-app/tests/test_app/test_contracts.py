class TestRunOperationSchema:
    """Phase 1 of the orchestrator refactor: `run_operations` table is
    persisted but not yet exposed via In/Out models. These tests pin the
    column shape so a later phase that adds RunOperationOut starts from a
    known-stable DB schema. They also catch accidental column drops in
    the gap between Phase 1 and Phase 4.

    Spec: docs/orchestrator-design.md §5.2.
    """

    def test_run_operations_table_exists(self):
        assert hasattr(db, "RunOperation"), (
            "RunOperation SQLModel must be defined in db_models.py — "
            "Phase 1 of the orchestrator refactor."
        )
        assert db.RunOperation.__tablename__ == "run_operations"

    def test_run_operations_columns_match_spec(self):
        expected = {
            "id", "run_id", "step_index", "operation_name",
            "params_json", "skip_if", "status",
            "databricks_run_id", "vibe_session_id",
            "parent_version_id", "output_version_id",
            "rollback_state_json", "error_message",
            "started_at", "completed_at", "created_at",
            "dispatched_widgets_json",
        }
        actual = {c.name for c in db.RunOperation.__table__.columns}
        assert expected == actual, (
            f"RunOperation columns drifted from §5.2 spec. "
            f"Missing: {expected - actual}; extra: {actual - expected}."
        )

    def test_run_operations_unique_constraint(self):
        """One op per step per run — orchestrator's start() relies on
        this to keep advance() retry-safe."""
        constraints = db.RunOperation.__table__.constraints
        unique_pairs = set()
        for c in constraints:
            cls_name = type(c).__name__
            if cls_name == "UniqueConstraint":
                unique_pairs.add(tuple(sorted(col.name for col in c.columns)))
        assert ("run_id", "step_index") in unique_pairs, (
            "RunOperation must have UNIQUE(run_id, step_index) — see §5.2."
        )

    def test_run_operations_run_id_indexed(self):
        """The orchestrator's poll loop queries by run_id; without an
        index it'd table-scan once per run on every advance() call."""
        run_id_col = db.RunOperation.__table__.c.run_id
        assert run_id_col.index, (
            "run_operations.run_id must be indexed for the orchestrator's "
            "poll-loop query."
        )

    def test_run_intent_column_exists(self):
        """Phase 5 retires ``run_type`` and ``rollback_plan`` in favour of
        ``Run.intent`` and per-step ``RunOperation.rollback_state_json``
        (orchestrator-design.md §5.1)."""
        col_names = {c.name for c in db.Run.__table__.columns}
        assert "intent" in col_names, "Run.intent must be persisted."
        assert "run_type" not in col_names, (
            "Run.run_type was retired in Phase 5; do not re-add it."
        )
        assert "rollback_plan" not in col_names, (
            "Run.rollback_plan was retired in Phase 5; rollback state "
            "now lives on RunOperation.rollback_state_json."
        )


