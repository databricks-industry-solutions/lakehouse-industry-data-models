"""Contract tests — verify field alignment across the triple model pattern.

For every entity, the contract is:
  - Every non-relationship, non-auto-generated field on a DB model must appear
    on its corresponding Out model.
  - Every field on an In model must exist on the DB model.

This catches drift between layers: if a field is added to the DB model but
forgotten in the Out model, the API silently drops it. If a field is added
to the In model but not the DB model, writes silently ignore it.
"""

