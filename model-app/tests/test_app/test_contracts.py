class TestMetamodelSeedConvergence:
    """Track 3 spike lock: EVERY iterable-version producer must seed
    ``_metamodel`` (else the produced version is un-iterable - the agent reads
    its parent model only from ``_metamodel``). All four converge on the single
    shared ``seed_metamodel_one`` helper, which is the one place that calls the
    canonical ``write_metamodel``. Static source checks so a new producer that
    forgets to seed, or a refactor that drops a call, fails here rather than
    silently shipping an un-iterable version. Mirrors the next-vibes lock."""

    def test_all_producers_call_shared_seed_helper(self):
        import inspect

        from vibe_modeling.backend.routes import import_root
        from vibe_modeling.backend.routes import businesses as businesses_route
        from vibe_modeling.backend.services import (
            dialog_import,
            industry_download,
            industry_kickstart,
            industry_prefix_fix,
        )

        # Both import dialogs seed through the shared dialog-import steps.
        for route in (import_root, businesses_route):
            assert "finish_dialog_import(" in inspect.getsource(route), route.__name__
        for mod in (
            dialog_import,        # the two import dialogs
            industry_kickstart,   # kickstart
            industry_download,    # download
            industry_prefix_fix,  # the pre-0.9.0 industry prefix fix re-seeds
        ):
            # Require the CALL syntax, not just the symbol, so dropping the
            # actual call while leaving the import/comment still fails here.
            assert "seed_metamodel_one(" in inspect.getsource(mod), (
                f"{mod.__name__} must seed _metamodel via seed_metamodel_one() - "
                f"an iterable-version producer that does not seed makes its "
                f"version un-iterable."
            )

    def test_shared_helper_calls_write_metamodel(self):
        """The convergence point actually calls the canonical writer - keep the
        write_metamodel( call-syntax lock here now that the four producers
        delegate to the shared helper."""
        import inspect

        from vibe_modeling.backend.services import import_metamodel_writer

        src = inspect.getsource(import_metamodel_writer.seed_metamodel_one)
        assert "write_metamodel(" in src

    def test_service_producers_bind_seed_helper_at_module_level(self):
        """Import-honesty: the two service producers use a MODULE-LEVEL import,
        so the name must be bound on the module (a missing import would 500 at
        runtime with NameError - and must not be masked by a test patching the
        attribute into existence)."""
        from vibe_modeling.backend.services import (
            industry_download,
            industry_kickstart,
        )

