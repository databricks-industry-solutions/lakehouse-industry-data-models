def _unique_column_tuples(table) -> set[tuple[str, ...]]:
    """Collect UNIQUE constraints off a SQLModel ``__table__`` as sorted
    column-name tuples — the same idiom as
    ``TestRunOperationSchema.test_run_operations_unique_constraint``."""
    out: set[tuple[str, ...]] = set()
    for c in table.constraints:
        if type(c).__name__ == "UniqueConstraint":
            out.add(tuple(sorted(col.name for col in c.columns)))
    return out


